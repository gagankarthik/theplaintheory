/** A fresh draft translation for a language, ready to store on a region. */
export function draftTranslation(code: LanguageCode): NoticeTranslation | null {
  const d = NOTICE_DRAFTS[code];
  if (!d) return null;
  return { copy: { ...d.copy }, categories: structuredClone(d.categories), status: "draft" };
}

/** A blank-ish translation that starts from the English source (for languages without a draft). */
export function englishStarter(): NoticeTranslation {
  return { copy: { ...DRAFT_SOURCE.copy }, categories: structuredClone(DRAFT_SOURCE.categories), status: "draft" };
}

export const draftNote = (code: LanguageCode) => NOTICE_DRAFTS[code]?.note;

