/**
 * Machine-assisted drafts of the default DPDPA notice in the 22 Eighth Schedule languages.
 *
 * Every draft is shipped with status "draft". They exist so a team can start from something
 * readable instead of a blank form; a native speaker must review the wording before the
 * translation is marked reviewed. The English source is deliberately short and literal so the
 * meaning survives translation.
 */

type Cats = Record<CategoryId, { label: string; description: string }>;
interface Draft {
  copy: BannerCopy;
  categories: Cats;
  /** extra guidance shown to the reviewer for this language */
  note?: string;
}

const c = (
  title: string,
  body: string,
  acceptAll: string,
  rejectAll: string,
  customize: string,
  save: string,
  policyLabel: string,
): BannerCopy => ({ title, body, acceptAll, rejectAll, customize, save, policyLabel });

const cats = (e: [string, string], f: [string, string], a: [string, string], m: [string, string]): Cats => ({
  essential: { label: e[0], description: e[1] },
  functional: { label: f[0], description: f[1] },
  analytics: { label: a[0], description: a[1] },
  marketing: { label: m[0], description: m[1] },
});

